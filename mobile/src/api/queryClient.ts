// Единственный экземпляр QueryClient — вынесен из _layout.tsx в свой модуль,
// чтобы session.signOut() мог почистить кэш напрямую, без контекста React.
//
// Это не косметика: без явной очистки на signOut кэш живёт в памяти между
// аккаунтами на одном устройстве (staleTime 30с и дольше, пока не истечёт).
// Второй пользователь после выхода первого на короткое время видит ЕГО
// команды/профиль/что угодно ещё закешированное — реальная утечка данных
// между аккаунтами, не только «старые данные мигают».

import { QueryClient } from '@tanstack/react-query';

export const queryClient = new QueryClient({
  defaultOptions: { queries: { retry: 1, staleTime: 30_000 } },
});
